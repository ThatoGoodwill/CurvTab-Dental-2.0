#!/usr/bin/env bash
# CurvTab Dental Laboratory Exchange and Closure — one-command installer V1
# Generated using the supplied 10-screen developer guide and source snapshot.
# No seed patients, no new finance ledger, no database reset or Docker volume deletion.
set -Eeuo pipefail
umask 077

ROOT="/workspaces/CurvTab-Dental-2.0"
ARCHIVE_STORE="/workspaces/.curvtab-safe-snapshots"
STAMP="$(date -u +%Y%m%d-%H%M%S)"
SAVE="$ARCHIVE_STORE/lab-prechange-$STAMP"
STAGING="$(mktemp -d /tmp/curvtab-lab-v1.XXXXXX)"
trap 'echo "LAB INSTALLER STOPPED. Preserve database and files. Prechange backup: '"$SAVE"'" >&2' ERR
trap 'rm -rf "$STAGING"' EXIT

if [[ ! -d "$ROOT/.git" || ! -f "$ROOT/frontend/src/App.tsx" || ! -f "$ROOT/backend/CurvTabDental.Infrastructure/Persistence/DentalDbContext.cs" ]]; then
  echo 'STOP: Codespace source tree does not match the expected CurvTab Dental layout.' >&2; exit 1
fi
cd "$ROOT"
if [[ -e backend/CurvTabDental.Domain/Entities/LaboratoryExchange.cs || -e frontend/src/pages/LaboratoryModule.tsx ]]; then
  echo 'STOP: A laboratory installer appears to have already run. Do not overwrite existing lab code. Inspect existing source before retrying.' >&2; exit 1
fi
for tool in docker python3 dotnet npm tar sha256sum; do
  command -v "$tool" >/dev/null || { echo "STOP: Missing tool $tool" >&2; exit 1; }
done
if ! docker exec curvtab-db pg_isready -U "$(docker exec curvtab-db printenv POSTGRES_USER)" >/dev/null 2>&1; then
  echo 'STOP: PostgreSQL curvtab-db must be healthy before backup.' >&2; exit 1
fi

mkdir -p "$SAVE"
echo '=== 1/10: SAVE VERIFIED PROJECT + DATABASE BACKUPS ==='
# Back up the whole source (including hidden files, .git, upload folders, local recovery scripts).
# Rebuildable dependencies are excluded. Original backup is never uploaded to a public repository.
tar -czf "$SAVE/complete-project-before-lab.tar.gz" \
  --exclude='*/node_modules' --exclude='*/obj' --exclude='*/bin' \
  --exclude='*/dist' --exclude='*/.next' --exclude='*/.cache' \
  -C /workspaces CurvTab-Dental-2.0
tar -tzf "$SAVE/complete-project-before-lab.tar.gz" >/dev/null
git bundle create "$SAVE/git-history.bundle" --all >/dev/null
git bundle verify "$SAVE/git-history.bundle" >/dev/null
git status --short > "$SAVE/prechange-git-status.txt"
DB_USER="$(docker exec curvtab-db printenv POSTGRES_USER)"
DB_NAME="$(docker exec curvtab-db printenv POSTGRES_DB)"
DB_PASS="$(docker exec curvtab-db printenv POSTGRES_PASSWORD)"
DB_PORT="$(docker port curvtab-db 5432/tcp | head -1 | awk -F: '{print $NF}')"
if [[ -z "$DB_NAME" || -z "$DB_USER" || -z "$DB_PASS" || ! "$DB_PORT" =~ ^[0-9]+$ ]]; then
  echo 'STOP: Unable to determine verified Docker PostgreSQL connection.' >&2; exit 1
fi
# Do not echo credentials.
docker exec curvtab-db pg_dump -U "$DB_USER" -d "$DB_NAME" -Fc > "$SAVE/postgresql-before-lab.dump"
docker exec -i curvtab-db pg_restore -l < "$SAVE/postgresql-before-lab.dump" > "$SAVE/dump-table-of-contents.txt"
[[ -s "$SAVE/postgresql-before-lab.dump" ]] || { echo 'STOP: Empty database backup.' >&2; exit 1; }
docker exec curvtab-db pg_dumpall -U "$DB_USER" --globals-only > "$SAVE/postgresql-global-roles.sql"
(cd "$SAVE" && sha256sum complete-project-before-lab.tar.gz postgresql-before-lab.dump git-history.bundle > SHA256SUMS)
echo "PRIVATE BACKUP VERIFIED: $SAVE"

# All current migrations must already be applied. Never layer this on an unfinished previous installer.
echo '=== 2/10: VALIDATE CURRENT MIGRATION HISTORY ==='
DB_USER="$DB_USER" DB_NAME="$DB_NAME" python3 - <<'PY'
import os, re, pathlib, subprocess, sys
base=pathlib.Path('backend/CurvTabDental.Infrastructure')
files={p.stem for p in base.rglob('*.cs') if re.match(r'^\d{14}_',p.stem) and not p.name.endswith('.Designer.cs')}
r=subprocess.run(['docker','exec','curvtab-db','psql','-U',os.environ['DB_USER'],'-d',os.environ['DB_NAME'], '-Atc', 'SELECT "MigrationId" FROM "__EFMigrationsHistory";'],capture_output=True,text=True)
if r.returncode: sys.exit('STOP: Could not inspect EF migration history: '+r.stderr)
applied=set(r.stdout.splitlines())
pending=sorted(files-applied)
if pending: sys.exit('STOP: Resolve these previously pending migrations before laboratory installation:\n'+'\n'.join(pending))
print('Existing application migrations match the database. Safe to generate new lab migration.')
PY

echo '=== 3/10: UNPACK LAB SOURCE ==='
# The installer embeds its own payload and does not download remote scripts.
mkdir -p "$STAGING/payload"
base64 --decode <<'LAB_PAYLOAD_BASE64' | tar -xz -C "$STAGING/payload"
